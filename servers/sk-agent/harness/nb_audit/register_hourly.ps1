# Register the hourly pre-audit task for the current user (no elevation). Dry-run by default:
# prints the generated launcher + the exact task XML and does nothing; -Apply writes the launcher
# and registers it. -Remove unregisters it.
# 2026-11-08: :05 -> :12. The GitHub REST bucket (5000/h per USER, shared fleet-wide)
# rolls over around :06-:08Z; every :05Z pass since 05:05Z 08/11 died on "rate limit
# exceeded" while the fresh window measured nearly empty minutes later. :12 lands
# 4-6 min after the rollover. Re-register with -Apply -Start 00:12 (dry-run default).
# 2026-11-16 (roo-extensions #4781 condition 4): the VBS launcher is GENERATED here, at
# registration time, into %LOCALAPPDATA%\nbaudit\bin -- absolute paths are baked into a
# generated artifact OUTSIDE the tree instead of being committed (outputs never enter the
# tree: a written file would dirty the checkout on every pass). It targets powershell.exe
# 5.1, present on every seat, not pwsh 7. The scripts stay 5.1-compatible.
param([switch]$Apply, [switch]$Remove, [string]$Name = 'nbaudit-hourly', [string]$Start = '00:12')
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$wrapper = Join-Path $here 'nb_audit_hourly.ps1'
$binDir = Join-Path $env:LOCALAPPDATA 'nbaudit\bin'
$vbs = Join-Path $binDir 'nb_audit_hourly.launcher.vbs'   # generated, invisible launcher (flicker fix #44)
$user = [System.Security.Principal.WindowsIdentity]::GetCurrent().Name
$begin = (Get-Date).Date.Add([TimeSpan]::Parse($Start)).ToString('s')

# VBS generation: visible-window suppression via `Run(..., 0, False)`; powershell.exe (5.1)
# targeted explicitly so the launcher resolves on every seat. ASCII, no BOM (wscript reads it).
$vbsContent = @"
' GENERATED by register_hourly.ps1 ($((Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ'))) --
' do not edit, do not commit: re-run register_hourly.ps1 -Apply to regenerate.
' Invisible launcher (flicker fix #44), targets powershell.exe 5.1 (always present).
CreateObject("WScript.Shell").Run "powershell.exe -NoProfile -WindowStyle Hidden -File ""$wrapper""", 0, False
"@

$xml = @"
<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.4" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo><Description>CoursIA #17073 pre-audit, mode (b): runner + delivery to the bots. Owner ai-01:vllm.</Description></RegistrationInfo>
  <Triggers>
    <TimeTrigger>
      <StartBoundary>$begin</StartBoundary>
      <Repetition><Interval>PT1H</Interval><StopAtDurationEnd>false</StopAtDurationEnd></Repetition>
      <Enabled>true</Enabled>
    </TimeTrigger>
  </Triggers>
  <Principals><Principal id="Author"><UserId>$user</UserId><LogonType>InteractiveToken</LogonType><RunLevel>LeastPrivilege</RunLevel></Principal></Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StartWhenAvailable>false</StartWhenAvailable>
    <ExecutionTimeLimit>PT50M</ExecutionTimeLimit>
    <Enabled>true</Enabled>
  </Settings>
  <Actions Context="Author">
    <Exec><Command>wscript.exe</Command><Arguments>"$vbs"</Arguments></Exec>
  </Actions>
</Task>
"@
if ($Remove) { Unregister-ScheduledTask -TaskName $Name -Confirm:$false; "removed $Name"; return }
if (-not $Apply) {
    "DRY-RUN: nothing changed. Would write '$vbs' with this content:"
    $vbsContent
    "Then register '$Name' for $user with this definition:"
    $xml
    return
}
New-Item -ItemType Directory -Force $binDir | Out-Null
# ASCII (default WriteAllText encoding is UTF-8 no BOM in .NET Framework; paths here are ASCII);
# an explicit ASCII encoding keeps wscript happy whatever the console codepage.
[System.IO.File]::WriteAllText($vbs, $vbsContent, [System.Text.Encoding]::ASCII)
"launcher written: $vbs"
# -Force: re-registration must UPDATE an existing task; without it Register-ScheduledTask fails
# with ResourceExists (0x800700b7) and silently leaves the old action in place (measured 16/11).
Register-ScheduledTask -TaskName $Name -Xml $xml -Force | Select-Object TaskName, State
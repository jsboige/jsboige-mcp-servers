# Hourly pre-audit pass (CoursIA #17073, mode (b)): produce fresh records, then deliver them.
# Run by the user-level scheduled task that register_hourly.ps1 creates. Record: _iteration_log/nb_audit_pilot/NOTES.md
# Series: 17107/17239/17357 = the original pilot (all at 0 remaining, kept: they cost 3 REST reads and
# pick up anything new). 17692 (02-ML-Cours) + 19451 = wave 1 of the converged Hermes+NanoClaw order
# (08/10 evening, user green light same day): one wave at a time, prod first, pass size at our call,
# joint re-evaluation after each wave. #19451 is a wide series (14 sections, 226 unchecked) --
# --subpath scopes it; the prefix switched Audio/ -> Image/ on 10/10 11:20Z when Audio/ hit 38/38
# checked with zero remaining (trigger recorded in the surveillance spec, PR #113). Audio/ notebooks
# stay covered: already-audited ones need nothing, PR-open ones are skipped by the runner itself.
# Image/ -> Video/ switch on 12/11 13:50Z: the runner reported 0 picked in Image/ (3 unchecked but
# already audited in comments) while NanoClaw had started auditing Video/ notebooks in FULL READ
# without pre-audit dossiers (01-3, 01-4, 02-2 audited 12/11 02:12-06:13Z) -- the exact cost the
# producer exists to cut. Dry-run before the switch: 3 Video notebooks selected, nothing written.
# The skip list the order named (PR #19868) was stale within hours (closed-superseded by #19854);
# the runner now derives per pass which notebooks an open PR is about to change and skips those by itself.
# Video/ -> Texte/ switch on 16/11 11:56Z, on CoursIA's arbitration (myia-ai-01:CoursIA, 12:47Z):
# the producer was stopped for SIX Video/ dossiers from 12/11 that NanoClaw never consumed
# (`--lookahead 6` reached, ok:true, 0 selected -- a legitimate idle, not a failure). CoursIA chose
# the wave switch over waiting: keeping the prefix would freeze production behind dossiers nobody
# reads. The six go to myia-po-2027:CoursIA (Video environment, already took 02-2 LTX in #26398).
# Dry-run before the switch: 2 Texte/ notebooks selected (10d_TensorSharp, 22_Evaluating_Generated_Text),
# nothing written. Video/ stays at 21 unchecked by US -- it is po-2027's now, and the runner's own
# PR-skip plus the audited-comments count mean nothing already covered is re-produced.
param([int[]]$Series = @(17107, 17239, 17357, 17692, 19451), [int]$PerSeries = 3,
      [string[]]$Subpath = @('19451:Texte/'), [string]$Python = '',
      [string]$Repo = 'd:/dev/CoursIA-skaudit')
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$logDir = Join-Path $env:LOCALAPPDATA 'nbaudit\logs'
New-Item -ItemType Directory -Force $logDir | Out-Null
$log = Join-Path $logDir ('hourly-{0:yyyyMMdd}.log' -f (Get-Date).ToUniversalTime())
$env:PYTHONIOENCODING = 'utf-8'
# Interpreter resolution (roo-extensions #4781 condition 3): -Python param, then
# NB_AUDIT_PYTHON env, then the sk-agent venv two levels up (the layout the harness has
# once it lives at mcps/internal/servers/sk-agent/harness/nb_audit/ -- that venv carries
# the `mcp` package; the ../..\sk_agent.py marker keeps an unrelated ../.. from matching),
# then whatever `python` resolves to on PATH. No hard-coded path.
$py = $Python
if (-not $py) { $py = $env:NB_AUDIT_PYTHON }
if (-not $py) {
    $venvPy = Join-Path $here '..\..\venv\Scripts\python.exe'
    if ((Test-Path $venvPy) -and (Test-Path (Join-Path $here '..\..\sk_agent.py'))) { $py = (Resolve-Path $venvPy).Path }
}
if (-not $py) { $py = 'python' }
Set-Location $here
function Stamp($m) { Add-Content $log ('=== {0:yyyy-MM-ddTHH:mm:ss}Z {1}' -f (Get-Date).ToUniversalTime(), $m) }

# The pass publishes a durable result. It CANNOT rely on its exit code: the scheduled task
# launches wscript.exe on a launcher VBS (GENERATED by register_hourly.ps1 into
# %LOCALAPPDATA%\nbaudit\bin -- never committed with absolute paths, roo-extensions #4781
# condition 4), whose `Run(..., 0, False)` does not wait
# and hands back nothing, so wscript itself always exits 0. Measured 08/10/2026: a VBS with that
# exact tail running a child that exits 7 returned 0. A 37 h outage (07/10 00:05Z -> 08/10 13:05Z,
# 32 consecutive rc=1 passes) therefore left `LastTaskResult` at 0 the whole time -- the log line
# was the only trace, and nothing read the log. The state file below is the signal that survives:
# one line, machine-readable, written on every pass including the failing ones, with a failure
# counter that makes a multi-day silence impossible to miss.
$stateFile = Join-Path (Split-Path -Parent $logDir) 'last-result.json'
function Write-State($runnerRc, $deliverRc) {
    # deliver_rc != 0 means a real send failed (nb_audit_deliver.py returns 1 only when some
    # message did not go out; "nothing to deliver" is 0), so both codes count as a failure.
    $ok = ($runnerRc -eq 0) -and ($deliverRc -eq 0)
    $prev = 0
    if (Test-Path $stateFile) {
        try { $prev = [int](Get-Content $stateFile -Raw | ConvertFrom-Json).consecutive_failures } catch { $prev = 0 }
    }
    $fails = 0
    if (-not $ok) { $fails = $prev + 1 }
    $state = [ordered]@{
        ts                   = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')
        runner_rc            = $runnerRc
        deliver_rc           = $deliverRc
        ok                   = $ok
        consecutive_failures = $fails
        series               = @($Series)
        per_series           = $PerSeries
        subpath              = @($Subpath)
    }
    # UTF-8 no BOM: Add-Content/Out-File would prepend one and break the parser (global rule).
    [System.IO.File]::WriteAllText($stateFile, ($state | ConvertTo-Json -Compress), [System.Text.UTF8Encoding]::new($false))
}

$rcRunner = -1
$rcDeliver = -1
try {
    Stamp 'runner'
    $runnerArgs = @('nb_audit_runner.py', '--series') + $Series + @('--per-series', $PerSeries)
    # The CoursIA checkout is an INPUT of the run, not a harness binding (F2, vllm#438): the
    # harness has no default for it, so this launcher passes the seat's path explicitly.
    if (-not $Repo) { $Repo = $env:NB_AUDIT_REPO }
    if (-not $Repo) { Stamp 'FAILED: no --Repo and no NB_AUDIT_REPO'; exit 2 }
    $runnerArgs += @('--repo', $Repo)
    foreach ($sp in $Subpath) { $runnerArgs += @('--subpath', $sp) }
    & $py @runnerArgs *>> $log
    $rcRunner = $LASTEXITCODE
    Stamp "runner rc=$rcRunner; deliver"
    & $py nb_audit_deliver.py --send *>> $log
    $rcDeliver = $LASTEXITCODE
    Stamp "deliver rc=$rcDeliver"
} finally {
    Write-State $rcRunner $rcDeliver
}

if ($rcRunner -ne 0) {
    Stamp "FAILED: runner rc=$rcRunner - NO records produced this pass"
}
# Still propagate the code for the day the task is re-pointed at pwsh directly; today the
# launcher discards it, which is exactly why the state file above carries the signal.
if ($rcRunner -ne 0) { exit $rcRunner }
if ($rcDeliver -ne 0) { exit $rcDeliver }
exit 0
